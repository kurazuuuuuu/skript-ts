import {
  add,
  bool,
  broadcast,
  call,
  command,
  defineFunction,
  dividedBy,
  equals,
  fishingApproachAngle,
  fishingBiteTime,
  fishingWaitTime,
  fmt,
  greaterThan,
  ifElse,
  lessThan,
  listAdd,
  localList,
  localVar,
  loopList,
  minus,
  num,
  onFishCast,
  param,
  player,
  plus,
  remove,
  returnValue,
  script,
  sendTitle,
  set,
  setFishingApproachAngle,
  setFishingBiteTime,
  setFishingWaitTime,
  str,
  times,
  timespan,
  variable,
  waitFor,
} from "../src/index.js";
import type { Script } from "../src/index.js";

// Core-language sample (phase 23): timespans as first-class
// values — literals of every unit, arithmetic, comparisons,
// eternity, typed function parameters, and the add / remove
// statements. Entirely core constructs, so it runs under both
// runtimes — the emitted .sk under Skript and the IR under the
// engine jar.
//
//   /tscalc    the value battery: every line is a broadcast of
//              the form "TS <label>=[<printed value>]"
//   /tswait    a 2-second wait from a timespan expression
//   /tstitle   a title whose three timings are expressions
//   /tsfish    arms the next cast: the fishing handler prints
//              the hook's default wait / bite / angle values,
//              retunes them, and prints the read-back
export const timespanScript: Script = script(
  defineFunction("tsId", [param("t", "timespan")], "timespan", [returnValue(localVar("t"))]),
  defineFunction("tsDefault", [param("t", "timespan", timespan(42, "seconds"))], "timespan", [returnValue(localVar("t"))]),
  defineFunction("tsCount", [param("ts", "timespans")], "number", [
    set(localVar("n"), num(0)),
    loopList(localList("ts"), [add(localVar("n"), num(1))]),
    returnValue(localVar("n")),
  ]),
  command("tscalc", null, [
    set(localVar("t"), timespan(5, "seconds")),
    set(localVar("big"), times(timespan(100000, "years"), num(100000000))),
    set(localVar("c100"), timespan(100, "ticks")),
    set(localVar("c90"), timespan(90, "seconds")),
    set(localVar("c2m"), timespan(2, "minutes")),
    set(localVar("v"), timespan(90, "seconds")),
    broadcast(fmt("TS lit90=[", localVar("v"), "]")),
    set(localVar("v"), timespan(100, "ticks")),
    broadcast(fmt("TS lit100t=[", localVar("v"), "]")),
    set(localVar("v"), timespan(25, "hours")),
    broadcast(fmt("TS lit25h=[", localVar("v"), "]")),
    set(localVar("v"), timespan(8, "days")),
    broadcast(fmt("TS lit8d=[", localVar("v"), "]")),
    set(localVar("v"), timespan(400, "days")),
    broadcast(fmt("TS lit400d=[", localVar("v"), "]")),
    set(localVar("v"), timespan(2, "months")),
    broadcast(fmt("TS lit2mo=[", localVar("v"), "]")),
    set(localVar("v"), timespan(1, "years")),
    broadcast(fmt("TS lit1y=[", localVar("v"), "]")),
    set(localVar("v"), timespan(0, "seconds")),
    broadcast(fmt("TS lit0=[", localVar("v"), "]")),
    set(localVar("v"), timespan(1, "ticks")),
    broadcast(fmt("TS lit1t=[", localVar("v"), "]")),
    set(localVar("v"), timespan(19, "ticks")),
    broadcast(fmt("TS lit19t=[", localVar("v"), "]")),
    set(localVar("v"), timespan(2.5, "seconds")),
    broadcast(fmt("TS lit2.5s=[", localVar("v"), "]")),
    set(localVar("v"), timespan(59.999, "seconds")),
    broadcast(fmt("TS lit59999=[", localVar("v"), "]")),
    set(localVar("v"), timespan(119.999, "seconds")),
    broadcast(fmt("TS lit119999=[", localVar("v"), "]")),
    broadcast(fmt("TS comp=[", plus(timespan(1, "hours"), timespan(30, "minutes")), "]")),
    broadcast(fmt("TS add=[", plus(localVar("t"), timespan(3, "seconds")), "]")),
    broadcast(fmt("TS sub=[", minus(localVar("t"), timespan(3, "seconds")), "]")),
    broadcast(fmt("TS subrev=[", minus(timespan(3, "seconds"), localVar("t")), "]")),
    broadcast(fmt("TS mul=[", times(localVar("t"), num(2)), "]")),
    broadcast(fmt("TS mulrev=[", times(num(2), localVar("t")), "]")),
    broadcast(fmt("TS div=[", dividedBy(localVar("t"), num(2)), "]")),
    broadcast(fmt("TS ratio=[", dividedBy(localVar("t"), timespan(3, "seconds")), "]")),
    broadcast(fmt("TS trunc=[", times(dividedBy(timespan(10, "ticks"), num(3)), num(3)), "]")),
    broadcast(fmt("TS inf=[", localVar("big"), "]")),
    broadcast(fmt("TS infminus=[", minus(localVar("big"), localVar("big")), "]")),
    broadcast(fmt("TS infzero=[", times(localVar("big"), num(0)), "]")),
    broadcast(fmt("TS mix=[", plus(localVar("t"), num(5)), "]")),
    broadcast(fmt("TS neg=[", times(localVar("t"), num(-1)), "]")),
    set(localVar("acc"), timespan(5, "seconds")),
    add(localVar("acc"), timespan(3, "seconds")),
    broadcast(fmt("TS stmtadd=[", localVar("acc"), "]")),
    remove(localVar("acc"), timespan(10, "seconds")),
    broadcast(fmt("TS stmtremove=[", localVar("acc"), "]")),
    set(variable("tsg"), timespan(33, "seconds")),
    broadcast(fmt("TS global=[", variable("tsg"), "]")),
    set(localVar("i"), num(2)),
    set(variable("tsl", localVar("i")), timespan(44, "seconds")),
    broadcast(fmt("TS listelem=[", variable("tsl", localVar("i")), "]")),
    ifElse(equals(localVar("t"), localVar("c100")), [broadcast(str("TS eq=true"))], [broadcast(str("TS eq=false"))]),
    ifElse(greaterThan(localVar("c2m"), localVar("c90")), [broadcast(str("TS gt=true"))], [broadcast(str("TS gt=false"))]),
    ifElse(lessThan(localVar("c90"), localVar("c2m")), [broadcast(str("TS lt=true"))], [broadcast(str("TS lt=false"))]),
    ifElse(equals(localVar("t"), num(5)), [broadcast(str("TS eqnum=true"))], [broadcast(str("TS eqnum=false"))]),
    ifElse(equals(localVar("big"), localVar("big")), [broadcast(str("TS infeq=true"))], [broadcast(str("TS infeq=false"))]),
    broadcast(fmt("TS fn=[", call("tsId", timespan(7, "seconds")), "]")),
    broadcast(fmt("TS fnvar=[", call("tsId", localVar("t")), "]")),
    broadcast(fmt("TS fndef=[", call("tsDefault"), "]")),
    listAdd(localList("args"), timespan(1, "seconds")),
    listAdd(localList("args"), timespan(2, "seconds")),
    listAdd(localList("args"), timespan(3, "seconds")),
    broadcast(fmt("TS fncount=[", call("tsCount", localList("args")), "]")),
  ]),
  command("tswait", null, [
    broadcast(str("TS wait start")),
    set(localVar("t"), timespan(1, "seconds")),
    waitFor(plus(localVar("t"), localVar("t"))),
    broadcast(str("TS wait end")),
  ]),

  command("tstitle", null, [
    set(localVar("stay"), timespan(3, "seconds")),
    sendTitle(player(), str("TS Title"), { fadeIn: timespan(1, "seconds"), stay: localVar("stay"), fadeOut: timespan(20, "ticks") }),
  ]),

  command("tsfish", null, [
    set(variable("tsfish"), bool(true)),
    broadcast(str("TS fish armed")),
  ]),

  onFishCast([
    ifElse(equals(variable("tsfish"), bool(true)), [
      broadcast(fmt("TS fish def min=[", fishingWaitTime("min"), "] max=[", fishingWaitTime("max"), "] bite=[", fishingBiteTime(), "] amin=[", fishingApproachAngle("min"), "] amax=[", fishingApproachAngle("max"), "]")),
      setFishingWaitTime("min", timespan(10, "seconds")),
      setFishingWaitTime("max", timespan(20, "seconds")),
      setFishingBiteTime(timespan(3, "seconds")),
      setFishingApproachAngle("min", num(45)),
      setFishingApproachAngle("max", num(270)),
      broadcast(fmt("TS fish set min=[", fishingWaitTime("min"), "] max=[", fishingWaitTime("max"), "] bite=[", fishingBiteTime(), "] amin=[", fishingApproachAngle("min"), "] amax=[", fishingApproachAngle("max"), "]")),
      set(variable("tsfish"), bool(false)),
    ]),
  ]),
);
